export const getPromptForStep = (role: AgentRole, symbol: string, context: string, subTask?: string) => {
  const dossierHeader = role !== AgentRole.INTELLIGENCE_OFFICER ? "\n### 以下为《全局共享情报档案 (Intelligence Dossier)》及前置报告，请基于此进行分析，严禁引用外部信息：\n" : "";
  
  const instructionPrefix = subTask ? `### 子任务检索指令：\n${subTask}\n\n` : "";

  return `目标标的: ${symbol}
${instructionPrefix}
${dossierHeader}
${context}

请严格遵循你的系统指令要求进行研判。请以专业的 Markdown 格式输出。`;
};
